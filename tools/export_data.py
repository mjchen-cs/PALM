"""
Export all data behind the paper into open formats (run from the repository root):

  data/raw/<EXP>.npz        frame-by-frame time series of every online run (float32, compressed)
  data/raw/<EXP>_index.csv  one row per run: run id, configuration tags, seed, scheme, cache key
  data/summary/<EXP>.csv    steady-state summary of every run (last 30% of the frames)

The raw runs are read from results/cache (written by experiments/run_online.py); the
configurations are regenerated by calling each experiment with go() intercepted, so the
mapping run <-> configuration is exact (same cache key as in the experiment).
Usage:  python3 tools/export_data.py
"""
import os, sys, csv, json, pickle
import numpy as np
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT); sys.path.insert(0, os.path.join(ROOT, "experiments"))
from palm.parallel import _key, CACHE

# frames/seeds used in run_v2.sh for each experiment
RUNS = {"E1": (10000, "1,2,3"), "E3": (8000, "1,2"), "E6": (8000, "1,2"), "E12": (8000, "1,2"),
        "E11": (8000, "1,2"), "E7": (8000, "1,2"), "E7b": (8000, "1,2"), "E6b": (8000, "1,2"),
        "E5": (6000, "1,2"), "E8": (8000, "1"), "E13": (10000, "1,2,3")}
SERIES = ["Q", "Y", "E", "Ees", "wrate", "off", "D", "hs", "hpro", "dt"]
DEV = ["perdev_P", "perdev_Jbit", "perdev_off", "perdev_D", "Qfinal"]
UNITS = {"Q": "mean data queue per WD (kbit)", "Y": "mean virtual energy queue per WD", "E": "mean WD power (W)",
         "Ees": "ES power (W)", "wrate": "delivered weighted rate (Mbps)", "off": "offloading ratio",
         "D": "processed data rate, all WDs (Mbps)", "hs": "handshakes in the frame", "hpro": "proactive handshakes",
         "dt": "decision time (s, wall clock)"}


def collect(name):
    frames, seeds = RUNS[name]
    os.environ["FRAMES"], os.environ["SEEDS"] = str(frames), seeds
    import importlib
    import run_online
    importlib.reload(run_online)
    jobs = []
    def fake_go(nm, cfgs, keep_traces=False):
        prof = None
        for tag, p, sch, kw in cfgs:
            for sd in run_online.SEEDS:
                args = (p, sch, run_online.FR, sd, kw)
                jobs.append((dict(tag, seed=sd, scheme=sch), args))
    run_online.go = fake_go
    getattr(run_online, name)()
    return jobs


def main():
    os.makedirs(os.path.join(ROOT, "data", "raw"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "data", "summary"), exist_ok=True)
    from palm.parallel import summarize
    readme = []
    for name in RUNS:
        jobs = collect(name)
        arrays, rows, miss = {}, [], 0
        for r, (tag, args) in enumerate(jobs):
            k = _key(args)
            path = os.path.join(CACHE, k + ".pkl")
            if not os.path.exists(path):
                miss += 1; continue
            o = pickle.load(open(path, "rb"))
            rid = f"run{r:04d}"
            for s in SERIES:
                arrays[f"{rid}/{s}"] = np.asarray(o[s], np.float32)
            for s in DEV:
                arrays[f"{rid}/{s}"] = np.asarray(o[s], np.float32)
            sm = summarize(o)
            row = dict(run=rid, **{k_: v for k_, v in tag.items()}, frames=args[2], cache_key=k)
            row.update({f"ss_{k_}": float(v) for k_, v in sm.items()})
            rows.append(row)
        np.savez_compressed(os.path.join(ROOT, "data", "raw", f"{name}.npz"), **arrays)
        keys = []
        for rw in rows:
            for k_ in rw:
                if k_ not in keys: keys.append(k_)
        for fn, cols in ((f"raw/{name}_index.csv", [k_ for k_ in keys if not k_.startswith("ss_")]),
                         (f"summary/{name}.csv", keys)):
            with open(os.path.join(ROOT, "data", fn), "w", newline="") as f:
                w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore"); w.writeheader(); w.writerows(rows)
        sz = os.path.getsize(os.path.join(ROOT, "data", "raw", f"{name}.npz")) / 1e6
        print(f"{name}: {len(rows)} runs exported, {miss} missing, {sz:.1f} MB", flush=True)
        readme.append((name, len(rows), miss))
    json.dump({"series": UNITS, "per_device": DEV, "experiments": readme},
              open(os.path.join(ROOT, "data", "raw", "FORMAT.json"), "w"), indent=1)


if __name__ == "__main__":
    main()
